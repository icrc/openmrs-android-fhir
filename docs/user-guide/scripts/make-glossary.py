"""Builds i18n/glossary.yml: the terms every translation must use.

    python scripts/make-glossary.py

* `ui`: the words of the app's screens, read from strings.xml in every language (never typed by hand).
* `domain`: the plain-language words of the guide (patient, visit, sync...). Where the app has its own
  word the translation uses it; the others are written here once, so that every chapter agrees.
* `do_not_translate`: names that stay as they are.
"""
import os
import re

import yaml

import gl

UI_KEYS = sorted(set(
    re.findall(r"\{\{([a-z0-9_]+)\}\}", "\n".join(
        open(os.path.join(gl.GUIDE, "content", "en", f), encoding="utf-8").read()
        for f in os.listdir(os.path.join(gl.GUIDE, "content", "en")) if f.endswith(".md")
    ))
))

DOMAIN = {
    "patient": {"en": "patient", "fr": "patient", "es": "paciente", "ru": "пациент", "ar": "المريض"},
    "patient_list": {"en": "patient list", "fr": "liste de patients", "es": "lista de pacientes", "ru": "список пациентов", "ar": "قائمة المرضى"},
    "location": {"en": "location", "fr": "lieu", "es": "ubicación", "ru": "локация", "ar": "الموقع"},
    "form": {"en": "form", "fr": "formulaire", "es": "formulario", "ru": "форма", "ar": "نموذج"},
    "encounter": {"en": "encounter", "fr": "consultation", "es": "encuentro", "ru": "встреча", "ar": "لقاء"},
    "visit": {"en": "visit", "fr": "visite", "es": "visita", "ru": "визит", "ar": "زيارة"},
    "sync": {"en": "sync", "fr": "synchronisation", "es": "sincronización", "ru": "синхронизация", "ar": "المزامنة"},
    "server": {"en": "server", "fr": "serveur", "es": "servidor", "ru": "сервер", "ar": "الخادم"},
    "tablet": {"en": "tablet", "fr": "tablette", "es": "tableta", "ru": "планшет", "ar": "الجهاز اللوحي"},
    "live_mode": {"en": "live mode", "fr": "mode en direct", "es": "modo en vivo", "ru": "режим онлайн", "ar": "الوضع المباشر"},
    "single_sign_on": {"en": "single sign-on", "fr": "authentification unique", "es": "inicio de sesión único", "ru": "единый вход", "ar": "تسجيل الدخول الموحّد"},
    "organisation": {"en": "organisation", "fr": "organisation", "es": "organización", "ru": "организация", "ar": "المؤسسة"},
}

DO_NOT_TRANSLATE = ["OpenMRS", "Wi-Fi", "QR", "PIN", "SSO", "Android", "PDF"]


def main():
    ui = {}
    for key in UI_KEYS:
        ui[key] = dict((lang, gl.strings(lang).get(key, "")) for lang in gl.LANGS)
    doc = {"do_not_translate": DO_NOT_TRANSLATE, "domain": DOMAIN, "ui": ui}
    path = os.path.join(gl.GUIDE, "i18n", "glossary.yml")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("# Generated by scripts/make-glossary.py: do not edit the `ui` part by hand (it comes from strings.xml).\n")
        yaml.safe_dump(doc, handle, allow_unicode=True, sort_keys=True, default_flow_style=False, width=120)
    print("wrote %s (%d ui terms, %d domain terms)" % (os.path.relpath(path, gl.GUIDE), len(ui), len(DOMAIN)))


if __name__ == "__main__":
    main()
