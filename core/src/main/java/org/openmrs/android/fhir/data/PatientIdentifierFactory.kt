package org.openmrs.android.fhir.data

import android.content.Context
import java.util.UUID
import kotlinx.coroutines.flow.first
import org.hl7.fhir.r4.model.CodeableConcept
import org.hl7.fhir.r4.model.Identifier
import org.hl7.fhir.r4.model.Location
import org.hl7.fhir.r4.model.Reference
import org.openmrs.android.fhir.Constants.PATIENT_LOCATION_IDENTIFIER_URL
import org.openmrs.android.fhir.auth.dataStore
import org.openmrs.android.fhir.data.database.AppDatabase

/**
 * Builds the identifiers a new patient is saved with. Registration uses it, and so does the first
 * sync after working as a guest (when the patients had no location to attach them to).
 */
class PatientIdentifierFactory(
  private val applicationContext: Context,
  private val database: AppDatabase,
) {
  /**
   * One identifier per selected identifier type, tied to [location]. Auto-generated types are kept
   * even without a value; the value is fetched from the server right before upload.
   */
  suspend fun locationIdentifiers(
    location: Location,
    fetchIdentifiers: Boolean = true,
  ): List<Identifier> {
    val identifiers = mutableListOf<Identifier>()
    val selectedIdentifierTypes =
      applicationContext.dataStore.data.first()[PreferenceKeys.SELECTED_IDENTIFIER_TYPES]?.toList()
        ?: return identifiers
    for (identifierTypeId in selectedIdentifierTypes) {
      val identifierType = database.dao().getIdentifierTypeById(identifierTypeId) ?: continue
      val isAutoGenerated = identifierType.isAutoGenerated ?: false
      val value = if (fetchIdentifiers) identifierType.uuid else null

      if (!isAutoGenerated && value.isNullOrBlank()) continue

      identifiers.add(
        newIdentifier(location).apply {
          this.value = value
          type = CodeableConcept().apply { text = identifierType.display }
        },
      )
    }
    return identifiers
  }

  /** Marker that makes the sync fetch real identifier values before uploading the patient. */
  fun unsyncedIdentifier(location: Location): Identifier =
    newIdentifier(location).apply {
      value = "unsynced"
      type = CodeableConcept().apply { text = "unsynced" }
    }

  private fun newIdentifier(location: Location): Identifier =
    Identifier().apply {
      id = UUID.randomUUID().toString()
      use = Identifier.IdentifierUse.OFFICIAL
      addExtension(
        PATIENT_LOCATION_IDENTIFIER_URL,
        Reference().apply {
          reference = location.id
          type = "Location"
          display = location.name
        },
      )
    }
}
