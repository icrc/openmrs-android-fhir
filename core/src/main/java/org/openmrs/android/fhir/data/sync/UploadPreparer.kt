package org.openmrs.android.fhir.data.sync

import android.content.Context
import com.google.android.fhir.FhirEngine
import com.google.android.fhir.search.search
import kotlinx.coroutines.flow.first
import org.hl7.fhir.r4.model.Patient
import org.openmrs.android.fhir.auth.dataStore
import org.openmrs.android.fhir.data.IdentifierTypeManager
import org.openmrs.android.fhir.data.PreferenceKeys
import org.openmrs.android.fhir.data.database.AppDatabase
import org.openmrs.android.fhir.data.remote.ApiManager
import org.openmrs.android.fhir.data.remote.ApiResponse
import org.openmrs.android.fhir.data.remote.model.IdentifierWrapper
import org.openmrs.android.fhir.data.remote.model.SessionLocation

/**
 * What has to be done to the data waiting on the device right before it is uploaded: the session
 * location is set on the server and the patients registered offline get the identifiers the server
 * generates for them. A full sync and a live upload ([LiveSync]) both run it.
 */
class UploadPreparer(
  private val context: Context,
  private val fhirEngine: FhirEngine,
  private val database: AppDatabase,
  private val apiManager: ApiManager,
  private val identifierTypeManager: IdentifierTypeManager,
) {

  suspend fun fetchIdentifierTypesIfEmpty() {
    val identifierTypes = database.dao().getIdentifierTypesCount()
    if (identifierTypes == 0) {
      identifierTypeManager.fetchIdentifiers()
    }
  }

  suspend fun embedIdentifiersInUnsyncedPatients() {
    // Setting location session first.
    context.dataStore.data.first()[PreferenceKeys.LOCATION_ID]?.let {
      apiManager.setLocationSession(SessionLocation(it))
    }
    // The source of the numbers is found from the identifier itself (its value is the id of its
    // type until the number is fetched), not from what the signed-in user selected: a patient
    // registered by someone else (imported from a file) has the types of that user.
    val sourceIdOfType = mutableMapOf<String, String?>()
    suspend fun sourceIdOf(identifierTypeId: String?): String? {
      if (identifierTypeId.isNullOrBlank()) return null
      return sourceIdOfType.getOrPut(identifierTypeId) {
        database
          .dao()
          .getIdentifierTypeById(identifierTypeId)
          ?.takeIf { it.isAutoGenerated == true }
          ?.sourceId
      }
    }

    val patients =
      fhirEngine
        .search<Patient> { filter(Patient.IDENTIFIER, { value = of(UNSYNCED_MARKER) }) }
        .map { it.resource }
        .toList()
    patients.forEach {
      val identifiers = it.identifier
      identifiers.forEach { identifier ->
        val sourceId = sourceIdOf(identifier.value)
        if (sourceId != null) {
          identifier.value = fetchIdentifierFromEndpoint(sourceId)
        }
      }
      // The marker that asked for this.
      identifiers.removeAll { identifier -> identifier.value == UNSYNCED_MARKER }
      it.identifier = identifiers
      fhirEngine.update(it)
    }
  }

  private suspend fun fetchIdentifierFromEndpoint(identifierId: String): String? {
    val response = apiManager.getIdentifier(identifierId)
    return when (response) {
      is ApiResponse.Success<IdentifierWrapper> -> response.data?.identifier
      else -> null
    }
  }
}

/** The value of the identifier a patient is saved with when real ones are to be fetched. */
private const val UNSYNCED_MARKER = "unsynced"
